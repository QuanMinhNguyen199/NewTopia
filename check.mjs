import {chromium} from '@playwright/test';
import fs from 'node:fs';
fs.mkdirSync('.impeccable/review',{recursive:true});
const browser=await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
const page=await browser.newPage({viewport:{width:2056,height:1200},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5173');
await page.screenshot({path:'.impeccable/review/desktop.png',fullPage:true});
await page.getByText('Bộ lọc',{exact:true}).click();
await page.getByPlaceholder('Số hiệu hoặc nội dung').fill('150/BC');
await page.getByRole('button',{name:'Hỏi',exact:true}).click();
await page.waitForTimeout(350);
if(await page.locator('.document').count()!==1)throw Error('Keyword filter failed');
await page.getByRole('button',{name:'Xóa bộ lọc'}).click();
if(await page.locator('.document').count()!==15)throw Error('Reset failed');
await page.getByRole('button',{name:'Báo cáo tổng hợp'}).click();
await page.getByRole('button',{name:'Tải báo cáo'}).waitFor();
await page.getByRole('button',{name:'Hỏi đáp'}).click();
await page.locator('.source .text-link').first().click();
if(!await page.locator('dialog').isVisible())throw Error('Source dialog failed');
await page.getByRole('button',{name:'Đóng',exact:true}).click();
await page.reload();
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'.impeccable/review/mobile.png',fullPage:true});
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
if(overflow)throw Error('Mobile horizontal overflow');
if(errors.length)throw Error(errors.join('\n'));
console.log('PASS: desktop and mobile rendering, keyword filter, reset, report tab, source dialog, no horizontal overflow or browser errors');
await browser.close();
